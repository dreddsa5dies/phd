package models

// Machine описывает машину
type Machine struct {
	// уникальный идентификатор
	ID string `json:"id" yaml:"id"`
	// тип оборудования
	Equipment []TypeEquipment `json:"equipment" yaml:"equipment"`
	// запас энергии
	Energy float64 `json:"energy" yaml:"energy"`
	// выполняемая задача
	AssignedTask *Task
}

// TypeEquipment - типы оборудования
// Примеры по технике:
//
// экскаватор : ковш, грейфер, рыхлитель (1, 3, 9)
// бульдозер : отвал, рыхлитель (2, 9)
// погрузчик : ковш, захват, вилы (для паллет) (1, 7, 14)
// снегоуборочная машина : плуг, фреза, щётка, метатель (6, 5, 4, 15)
// автогрейдер : нож-отвал (11)
// виброплита : трамбовочное устройство, виброплита (8, 13)
// конвейер : конвейер ленточный (10)
// скрепер : скребок (12)
type TypeEquipment uint

// Коды типов и примеры машин-носителей соответствуют ведомостям потребности
// проектов организации строительства М‑11 и М‑12.
const (
	Bucket TypeEquipment = iota + 1 // ковш
	// Примеры: экскаваторы ЭО‑4321, ЭО‑4321А, ЕК‑270, ЭО‑4121, ЭО‑4225;
	//          погрузчики фронтальные ТО‑18; экскаваторы-погрузчики ЭО‑2626ДТ.

	Dump // отвал
	// Примеры: бульдозеры Б10ПМ, ДЗ‑101А, ДТ‑75, Komatsu D39, CAT D6M LGP;
	//          автогрейдеры ДЗ‑98, ДЗ‑180 (передний отвал).

	Grapple // грейфер
	// Примеры: экскаваторы с грейферным ковшом (ЭО‑4121, ЭО‑4321);
	//          краны-манипуляторы для погрузки леса и металлолома.

	Brushes // щётки
	// Примеры: поливомоечные и подметально-уборочные машины КО‑823, КПМ‑130;
	//          снегоуборочные машины; роботизированные комплексы «Пиксель».

	Cutter // фреза
	// Примеры: дорожные фрезы Wirtgen W200F; грунтосмесительные машины Д‑391А;
	//          снегоуборочные машины (фрезерно-роторные).

	Plow // плуг
	// Примеры: снегоуборочные машины (отвальное оборудование);
	//          автогрейдеры ДЗ‑98, ДЗ‑180 с плужным снегоочистителем.

	Catch // захват
	// Примеры: погрузчики (захват для брёвен, труб); краны-манипуляторы.

	Tamp // трамбовочное устройство
	// Примеры: пневмотрамбовки; экскаваторы с навесной трамбующей плитой.

	Ripper // рыхлитель
	// Примеры: бульдозеры Б10ПМ, ДЗ‑101А (задний рыхлитель);
	//          экскаваторы ЭО‑4321 (сменное оборудование рыхлитель).

	Scraper // скребок
	// Примеры: скреперы; коммунальные машины для очистки дорог;
	//          роботизированные комплексы «Пиксель» (скребковое оборудование).

	Conveyor // конвейер ленточный
	// Примеры: асфальтоукладчики Vogele Super 1900, Titan;
	//          перегружатели асфальтобетонной смеси SB‑2500B.

	Knife // нож-отвал автогрейдера
	// Примеры: автогрейдеры ДЗ‑98, ДЗ‑180, ДЗ‑31‑1 (основной рабочий орган).

	VCompactor // виброплита / вибровалец
	// Примеры: виброплиты ВП‑2‑4‑1, TSS‑HCR60K;
	//          виброкатки Bomag BW211D‑4, BW177D‑5.

	Pitchfork // вилы для паллет
	// Примеры: погрузчики фронтальные и вилочные;
	//          экскаваторы-погрузчики ЭО‑2626ДТ (сменное оборудование).

	Thrower // метатель
	// Примеры: снегоуборочные машины (роторные снегоочистители);
	//          распределители дорожно-строительных материалов ДС‑54.

	Sprayer // распылитель / форсунка
	// Примеры: автогудронаторы ДС‑142Б (розлив битумной эмульсии);
	//          поливомоечные машины КО‑823, КПМ‑130 (распыление воды);
	//          агрегаты для нанесения плёнкообразующих материалов.

	Drill // буровое оборудование
	// Примеры: буровые машины БМ‑302М; бурильно-крановые установки;
	//          установки горизонтального направленного бурения Vermeer.

	PileDriver // сваебойное / вибропогружающее оборудование
	// Примеры: сваебойные установки Junttan PM‑20;
	//          вибропогружатели Starke SV‑150/160, ICE1423‑C, Muller.

	CraneHook // крюк крана (для монтажных задач)
	// Примеры: автокраны КС‑4362, КС‑55727 («Ивановец»);
	//          гусеничные краны СКГ‑63/100, Liebherr HS855HD.

	Mixer // смеситель / бетоносмеситель
	// Примеры: автобетоносмесители КамАЗ‑55111;
	//          мобильные растворобетонные узлы Elkon Quick Master 60;
	//          асфальтосмесительные установки Ammann BlackMove‑II‑320.

	Seeder // сеялка / гидросеялка
	// Примеры: агрегаты для посева трав ЦНИИС АДТС‑2;
	//          машины для гидропосева многолетних трав.

	Marker // маркировочное оборудование
	// Примеры: маркировочные машины ДС‑18А (нанесение дорожной разметки).

	PumpUnit // насосная установка
	// Примеры: водоотливные насосы ГНОМ 25‑20, ГНОМ 10‑10;
	//          насосные станции для водопонижения.

	CompressorUnit // компрессорная станция
	// Примеры: передвижные компрессоры ПКС, ЗИФ ПВ 10/07;
	//          дизельные компрессорные станции.

	GeneratorUnit // электрогенераторная установка
	// Примеры: дизельные электростанции ЭД‑100, ЭД‑500 (на одноосном прицепе);
	//          сварочные агрегаты АДД.
)

func IntersectTypeEquipment(in TypeEquipment, t []TypeEquipment) bool {
	for i := range t {
		if t[i] == in {
			return true
		}
	}
	return false
}

func TotalEnergyMachines(in []Machine) float64 {
	total := 0
	for i := range in {
		total += int(in[i].Energy)
	}
	return float64(total)
}
